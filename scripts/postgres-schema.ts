/**
 * npm run db:postgres
 *
 * Run after any change to prisma/schema.prisma. It:
 *   1. writes prisma/postgres/schema.prisma, the Postgres copy;
 *   2. asks Prisma for the SQL that creates every table, and saves it as
 *      src/data/postgres/schema-sql.ts, which the app runs on start;
 *   3. generates the Postgres Prisma client.
 *
 * Commit the two written files. The test in src/data/postgres fails if they
 * fall behind the main schema.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { makeIdempotent, toPostgresSchema } from '../src/data/postgres/schema-text';

const root = process.cwd();
const sourcePath = path.join(root, 'prisma', 'schema.prisma');
const targetPath = path.join(root, 'prisma', 'postgres', 'schema.prisma');
const sqlModulePath = path.join(root, 'src', 'data', 'postgres', 'schema-sql.ts');

/** Hand written additions for later changes Prisma's create script cannot express. */
const EXTRA_STATEMENTS: string[] = [
  // Added after the first hosted setup could exist.
  `ALTER TABLE "Attendee" ADD COLUMN IF NOT EXISTS "email" TEXT NOT NULL DEFAULT '';`,
  `ALTER TABLE "Photo" ADD COLUMN IF NOT EXISTS "storageKey" TEXT NOT NULL DEFAULT '';`,
];

mkdirSync(path.dirname(targetPath), { recursive: true });
writeFileSync(targetPath, toPostgresSchema(readFileSync(sourcePath, 'utf8')));
console.log('Wrote prisma/postgres/schema.prisma');

const createScript = execFileSync(
  'npx',
  ['prisma', 'migrate', 'diff', '--from-empty', '--to-schema', targetPath, '--script'],
  { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
);
const sql = [makeIdempotent(createScript), ...EXTRA_STATEMENTS].join('\n\n');

writeFileSync(
  sqlModulePath,
  [
    '// GENERATED by `npm run db:postgres` from prisma/schema.prisma. Do not edit.',
    '// Safe to run on every start: every statement is "if not exists".',
    '',
    `export const POSTGRES_SCHEMA_SQL = ${JSON.stringify(sql)};`,
    '',
  ].join('\n'),
);
console.log('Wrote src/data/postgres/schema-sql.ts');

execFileSync('npx', ['prisma', 'generate', `--schema=${targetPath}`], { stdio: 'inherit' });
